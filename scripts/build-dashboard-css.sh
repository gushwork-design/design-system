#!/usr/bin/env bash
# Build the dashboard system's three deliverables from their partials.
#
#   exports/dashboard/css/NN-*.css            -> exports/dashboard/dashboard.css
#   exports/dashboard/js/NN-*.js              -> exports/dashboard/dashboard.js
#   exports/dashboard/registry-parts/*.json   -> exports/dashboard/component-registry.json
#   skills/gushwork-dashboard/templates/analytics-overview/ -> web/previews/dashboard/pages/ (the review drawer's copy)
#                                                          -> templates/analytics-overview/ (the templates folder's copy)
#   skills/gushwork-dashboard/templates/support-ops-app/    -> web/previews/dashboard/pages/support-ops-app/ (the review drawer's copy of the five pages)
#   skills/gushwork-reports/templates/growth-report/        -> web/previews/dashboard/pages/growth-report.html (the review drawer's copy)
#                                                          -> templates/growth-report/ (the templates folder's copy)
#
# Edit the PARTIALS, never the built files: the next run overwrites them. Partials are joined in
# filename order, so the number prefix is the cascade order (00 base, 10 shell, 20 actions, ...).
#
# Usage:  bash scripts/build-dashboard-css.sh          # rebuild
#         bash scripts/build-dashboard-css.sh --check  # exit 1 if a built file is out of date
set -euo pipefail
cd "$(dirname "$0")/.."
D=exports/dashboard

# The template's preview copy for the review drawer: the same page with its repo-relative links turned into
# the deploy's absolute ones. Written under web/previews, which the site serves to signed-in people only, so
# a template waiting on review is not public. The stamp's registry URL is blanked in this copy only, so the
# build notice stays quiet while the live registry is the old one and reviewing never reports on itself.
TPL=skills/gushwork-dashboard/templates/analytics-overview/analytics-overview.html
page_preview() {  # $1 = output file
  mkdir -p "$(dirname "$1")"
  perl -pe 's#\.\./\.\./\.\./\.\./foundation/#/foundation/#g; s#\.\./\.\./\.\./\.\./exports/#/exports/#g; s#"registry":"https://[^"]*"#"registry":""#' "$TPL" > "$1"
}
# The same template, shipped beside the other documents and pages in templates/ (templates/<name>/ is where a person
# looks first). The skill's copy is the source; this one is generated from it with the links re-based two levels
# deep (templates/analytics-overview/ -> the repo root), so the two cannot drift. The README beside it is hand-written.
# The multi-page support operations template: the same links-made-absolute and blanked-stamp treatment, applied to every
# page, with the scripts and data file copied beside them so the pages still run as a set.
APP=skills/gushwork-dashboard/templates/support-ops-app
app_preview() {  # $1 = output dir
  rm -rf "$1"; mkdir -p "$1"
  cp "$APP"/*.js "$1"/
  # The hub serves pages with clean URLs and no trailing slash (web/vercel.json), so a folder's index.html is served at the bare
  # folder URL and every relative script and link then resolves one folder up. The review copy therefore has no index.html:
  # the Overview is overview.html, and the links to it say so. The template itself keeps index.html.
  for f in "$APP"/*.html; do
    out="$1/$(basename "$f")"; [ "$(basename "$f")" = "index.html" ] && out="$1/overview.html"
    perl -pe 's#\.\./\.\./\.\./\.\./foundation/#/foundation/#g; s#\.\./\.\./\.\./\.\./exports/#/exports/#g; s#"registry":"https://[^"]*"#"registry":""#; s#(href|data-nav)="index\.html"#$1="overview.html"#g' "$f" > "$out"
  done
}
templates_copy() {  # $1 = output file
  mkdir -p "$(dirname "$1")"
  perl -pe 's#\.\./\.\./\.\./\.\./foundation/#../../foundation/#g; s#\.\./\.\./\.\./\.\./exports/#../../exports/#g' "$TPL" > "$1"
}
# The reports skill's template: the same two treatments as the overview. Its source is in the skill; the hub's review copy
# gets absolute links and a blanked stamp registry; the templates/ copy gets links re-based two levels deep. render.sh and
# the README are not copied (render.sh needs the skill's folder depth; the README beside the copy is hand-written).
RPT=skills/gushwork-reports/templates/growth-report/growth-report.html
report_page_preview() {  # $1 = output file
  mkdir -p "$(dirname "$1")"
  perl -pe 's#\.\./\.\./\.\./\.\./foundation/#/foundation/#g; s#\.\./\.\./\.\./\.\./exports/#/exports/#g; s#"registry":"https://[^"]*"#"registry":""#' "$RPT" > "$1"
}
report_templates_copy() {  # $1 = output file
  mkdir -p "$(dirname "$1")"
  perl -pe 's#\.\./\.\./\.\./\.\./foundation/#../../foundation/#g; s#\.\./\.\./\.\./\.\./exports/#../../exports/#g' "$RPT" > "$1"
}
build() {  # $1 = output dir to write into
  local out="$1"; mkdir -p "$out"
  { echo "/* GENERATED by scripts/build-dashboard-css.sh from exports/dashboard/css/*.css — do not edit. */"
    for f in $(ls $D/css/*.css | sort); do printf '\n/* ==== %s ==== */\n' "$(basename "$f")"; cat "$f"; done
  } > "$out/dashboard.css"
  { echo "/* GENERATED by scripts/build-dashboard-css.sh from exports/dashboard/js/*.js — do not edit. */"
    echo "window.GD = window.GD || {};"
    if ls $D/js/*.js >/dev/null 2>&1; then
      for f in $(ls $D/js/*.js | sort); do printf '\n/* ==== %s ==== */\n(function(){\n' "$(basename "$f")"; cat "$f"; printf '\n})();\n'; done
    fi
  } > "$out/dashboard.js"
  python3 - "$D" "$out" <<'PY'
import json, glob, sys, os
d, out = sys.argv[1], sys.argv[2]
comps = {}
for p in sorted(glob.glob(f"{d}/registry-parts/*.json")):
    for k, v in json.load(open(p)).items():
        if k in comps: sys.exit(f"duplicate component key {k!r} in {p}")
        comps[k] = v
reg = {"$comment": [
  "Per-component versions for the dashboard surface. Built by scripts/build-dashboard-css.sh from",
  "registry-parts/*.json — edit the parts, never this file. Bump a component's version in the same",
  "commit that changes its spec; scripts/check-drift.sh reads this and a build's stamp. breaking=true",
  "when an existing build renders WRONG until updated. The review block is written by the review loop."],
  "registryVersion": "2.0.0", "components": dict(sorted(comps.items()))}
# ensure_ascii=False on purpose: the review loop writes this file too (the site's Save commits straight to main, and review-pass.sh does),
# both with raw unicode. Escaping the em dash here made every review decision look like "out of date" to --check and stopped a publish.
old = f"{d}/component-registry.json"
if os.path.exists(old):
    prev = json.load(open(old))
    if "review" in prev: reg["review"] = prev["review"]
json.dump(reg, open(f"{out}/component-registry.json", "w"), indent=2, ensure_ascii=False); open(f"{out}/component-registry.json", "a").write("\n")
print(f"{len(comps)} components")
PY
}
case "${1:-}" in
  --check)
    tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
    build "$tmp" >/dev/null
    for f in dashboard.css dashboard.js component-registry.json; do
      cmp -s "$tmp/$f" "$D/$f" || { echo "$D/$f is out of date — run: bash scripts/build-dashboard-css.sh" >&2; exit 1; }
    done
    page_preview "$tmp/page.html"
    cmp -s "$tmp/page.html" web/previews/dashboard/pages/analytics-overview.html \
      || { echo "web/previews/dashboard/pages/analytics-overview.html is out of date — run: bash scripts/build-dashboard-css.sh" >&2; exit 1; }
    app_preview "$tmp/app"
    diff -rq "$tmp/app" web/previews/dashboard/pages/support-ops-app >/dev/null 2>&1 \
      || { echo "web/previews/dashboard/pages/support-ops-app is out of date — run: bash scripts/build-dashboard-css.sh" >&2; exit 1; }
    templates_copy "$tmp/tpl.html"
    cmp -s "$tmp/tpl.html" templates/analytics-overview/analytics-overview.html \
      || { echo "templates/analytics-overview/analytics-overview.html is out of date — run: bash scripts/build-dashboard-css.sh" >&2; exit 1; }
    report_page_preview "$tmp/report.html"
    cmp -s "$tmp/report.html" web/previews/dashboard/pages/growth-report.html \
      || { echo "web/previews/dashboard/pages/growth-report.html is out of date — run: bash scripts/build-dashboard-css.sh" >&2; exit 1; }
    report_templates_copy "$tmp/report-tpl.html"
    cmp -s "$tmp/report-tpl.html" templates/growth-report/growth-report.html \
      || { echo "templates/growth-report/growth-report.html is out of date — run: bash scripts/build-dashboard-css.sh" >&2; exit 1; }
    echo "$D built files are current." ;;
  "") build "$D"; page_preview web/previews/dashboard/pages/analytics-overview.html
      app_preview web/previews/dashboard/pages/support-ops-app
      templates_copy templates/analytics-overview/analytics-overview.html
      report_page_preview web/previews/dashboard/pages/growth-report.html
      report_templates_copy templates/growth-report/growth-report.html
      echo "built $D/dashboard.css, dashboard.js, component-registry.json, and the template preview" ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac
